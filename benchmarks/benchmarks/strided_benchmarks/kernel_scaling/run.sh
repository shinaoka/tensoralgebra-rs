#!/usr/bin/env bash
# Build and run the kernel scaling page against an arbitrary strided-rs tree.
#
#   STRIDED_RS_DIR=/path/to/strided-rs run.sh build
#   STRIDED_RS_DIR=/path/to/strided-rs run.sh check [THREADS]
#   STRIDED_RS_DIR=/path/to/strided-rs run.sh rust THREADS
#   run.sh julia THREADS
#
# The suite Cargo.toml points at ../strided-rs. To measure any other tree
# without editing it, this script writes a standalone manifest under
# target/kernel-scaling/<rev>/ whose only path dependency is
# $STRIDED_RS_DIR/strided-kernel. Nothing outside target/ and data/results/
# is written, so no worktree path is ever committed.
#
# Environment: STRIDED_RS_DIR (default ../strided-rs), CPUS (Linux taskset
# list, default 0-(THREADS-1)), OUTPUT_DIR, RUSTFLAGS (default
# "-C target-cpu=native"), plus the binary's BENCH_RUNS, BENCH_WARMUP,
# KERNEL_SCALING_SHRINK and BENCH_FILTER.
set -euo pipefail

page=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$page/../../.." && pwd)
strided_rs=$(cd "${STRIDED_RS_DIR:-"$root/../strided-rs"}" && pwd)
[[ -f "$strided_rs/strided-kernel/Cargo.toml" ]] || {
    echo "no strided-kernel crate under $strided_rs" >&2
    exit 1
}

rev=$(git -C "$strided_rs" rev-parse --short=12 HEAD)
if [[ -n "$(git -C "$strided_rs" status --porcelain --untracked-files=no)" ]]; then
    rev="$rev-dirty"
    echo "warning: $strided_rs has uncommitted changes; results are labelled $rev" >&2
fi

build_dir="$root/target/kernel-scaling/$rev"
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-"$build_dir/target"}"
export RUSTFLAGS="${RUSTFLAGS:-"-C target-cpu=native"}"
bin="$CARGO_TARGET_DIR/release/kernel_scaling"
out=${OUTPUT_DIR:-"$root/data/results/kernel-scaling-$rev"}

write_manifest() {
    mkdir -p "$build_dir"
    cat >"$build_dir/Cargo.toml" <<EOF
# Generated by kernel_scaling/run.sh; do not commit.
[workspace]

[package]
name = "kernel-scaling"
version = "0.0.0"
edition = "2021"
publish = false

[[bin]]
name = "kernel_scaling"
path = "$page/kernel_scaling.rs"

[dependencies]
strided-kernel = { path = "$strided_rs/strided-kernel", default-features = false, features = ["parallel", "simd"] }
rayon = "1"
num-complex = "0.4"

[profile.release]
debug = 1
EOF
    # Reuse the suite lock file as a starting point so shared crates resolve
    # to the same versions; cargo prunes and extends it as needed.
    if [[ ! -f "$build_dir/Cargo.lock" && -f "$root/Cargo.lock" ]]; then
        cp "$root/Cargo.lock" "$build_dir/Cargo.lock"
    fi
}

build() {
    write_manifest
    echo "==> building kernel_scaling against $strided_rs ($rev)" >&2
    STRIDED_RS_REV="$rev" cargo build --release --manifest-path "$build_dir/Cargo.toml" >&2
}

# Run a command pinned to `threads` CPUs where the platform allows it.
pinned() {
    local threads=$1
    shift
    if command -v taskset >/dev/null 2>&1; then
        taskset -c "${CPUS:-0-$((threads - 1))}" "$@"
    else
        echo "note: taskset unavailable on $(uname -s); CPU pinning not applied" >&2
        "$@"
    fi
}

cmd=${1:-}
case "$cmd" in
build)
    build
    ;;
check)
    build
    threads=${2:-4}
    pinned "$threads" "$bin" --threads "$threads"
    ;;
rust)
    threads=${2:?usage: run.sh rust THREADS}
    build
    mkdir -p "$out"
    csv="$out/rust_${threads}t.csv"
    echo "==> rust ${threads}T, strided-rs $rev, writing $csv" >&2
    RAYON_NUM_THREADS="$threads" pinned "$threads" "$bin" --threads "$threads" --time | tee "$csv"
    ;;
julia)
    threads=${2:?usage: run.sh julia THREADS}
    mkdir -p "$out"
    csv="$out/julia_${threads}t.csv"
    echo "==> julia ${threads}T, writing $csv" >&2
    JULIA_NUM_THREADS="$threads" pinned "$threads" \
        julia --project="$root" --startup-file=no "$page/kernel_scaling.jl" --time | tee "$csv"
    ;;
julia-check)
    threads=${2:-4}
    JULIA_NUM_THREADS="$threads" julia --project="$root" --startup-file=no "$page/kernel_scaling.jl"
    ;;
*)
    echo "usage: run.sh {build|check [T]|rust T|julia T|julia-check [T]}" >&2
    exit 2
    ;;
esac
